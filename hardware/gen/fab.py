def gy(y):
    return -y


def c6(v):
    return str(int(round(v * 1e6)))


class Gerber:
    def __init__(self, func, polarity="Positive"):
        self.lines = ["G04 STM32 CAN ECU rev A - generated by hardware/gen/fab.py*",
                      "%TF.GenerationSoftware,custom,can-ecu-gen,1.0*%",
                      "%TF.ProjectId,CAN_ECU,00000000-0000-0000-0000-000000000000,A*%",
                      f"%TF.FileFunction,{func}*%", f"%TF.FilePolarity,{polarity}*%",
                      "%FSLAX46Y46*%", "%MOMM*%", "%LPD*%", "G01*"]
        self.aps = {}
        self.body = []
        self.cur_ap = None
        self.pol = "D"

    def ap(self, kind, *dims):
        key = (kind,) + tuple(round(d, 4) for d in dims)
        if key not in self.aps:
            n = 10 + len(self.aps)
            self.aps[key] = n
        return self.aps[key]

    def _sel(self, n):
        if self.cur_ap != n:
            self.body.append(f"D{n}*")
            self.cur_ap = n

    def polarity(self, p):
        if p != self.pol:
            self.body.append(f"%LP{p}*%")
            self.pol = p

    def flash_circle(self, x, y, d):
        self._sel(self.ap("C", d))
        self.body.append(f"X{c6(x)}Y{c6(gy(y))}D03*")

    def flash_rect(self, x, y, w, h):
        self._sel(self.ap("R", w, h))
        self.body.append(f"X{c6(x)}Y{c6(gy(y))}D03*")

    def flash_obround(self, x, y, w, h):
        self._sel(self.ap("O", w, h))
        self.body.append(f"X{c6(x)}Y{c6(gy(y))}D03*")

    def line(self, a, b, w):
        self._sel(self.ap("C", w))
        self.body.append(f"X{c6(a[0])}Y{c6(gy(a[1]))}D02*")
        self.body.append(f"X{c6(b[0])}Y{c6(gy(b[1]))}D01*")

    def region(self, pts):
        self.body.append("G36*")
        self.body.append(f"X{c6(pts[0][0])}Y{c6(gy(pts[0][1]))}D02*")
        for p in pts[1:] + [pts[0]]:
            self.body.append(f"X{c6(p[0])}Y{c6(gy(p[1]))}D01*")
        self.body.append("G37*")

    def save(self, path):
        out = list(self.lines)
        for key, n in sorted(self.aps.items(), key=lambda x: x[1]):
            kind = key[0]
            if kind == "C":
                out.append(f"%ADD{n}C,{key[1]:.4f}*%")
            elif kind == "R":
                out.append(f"%ADD{n}R,{key[1]:.4f}X{key[2]:.4f}*%")
            elif kind == "O":
                out.append(f"%ADD{n}O,{key[1]:.4f}X{key[2]:.4f}*%")
        out += self.body
        if self.pol != "D":
            out.append("%LPD*%")
        out.append("M02*")
        open(path, "w").write("\n".join(out) + "\n")


def rounded_rect_pts(cx, cy, w, h, r, rot, n=4):
    """polygon of a (rounded) rectangle, rotation multiple of 90."""
    if rot % 180 == 90:
        w, h = h, w
    r = min(r, w / 2, h / 2)
    pts = []
    corners = [(cx + w / 2 - r, cy - h / 2 + r, -90, 0), (cx + w / 2 - r, cy + h / 2 - r, 0, 90),
               (cx - w / 2 + r, cy + h / 2 - r, 90, 180), (cx - w / 2 + r, cy - h / 2 + r, 180, 270)]
    for x, y, a0, a1 in corners:
        if r <= 1e-6:
            pts.append((x, y))
            continue
        for i in range(n + 1):
            a = math.radians(a0 + (a1 - a0) * i / n)
            pts.append((x + r * math.cos(a), y + r * math.sin(a)))
    return pts


def draw_pad(g, p, grow=0.0):
    """draw pad copper (optionally grown by `grow`) with the current polarity."""
    w, h = p.w + 2 * grow, p.h + 2 * grow
    if p.shape == "circle":
        g.flash_circle(p.x, p.y, w)
    elif p.shape == "oval":
        if p.rot % 180 == 90:
            w, h = h, w
        g.flash_obround(p.x, p.y, w, h)
    elif p.shape == "rect" and grow == 0:
        if p.rot % 180 == 90:
            w, h = h, w
        g.flash_rect(p.x, p.y, w, h)
    else:
        r = (min(p.w, p.h) * p.pad.rratio if p.shape == "roundrect" else 0.0) + grow
        g.region(rounded_rect_pts(p.x, p.y, w, h, r, p.rot))


