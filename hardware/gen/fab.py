def render_gerber(path, ax, color, bg):
    txt = open(path).read()
    aps = {}
    for m in re.finditer(r"%ADD(\d+)([CRO]),([\d.]+)(?:X([\d.]+))?\*%", txt):
        aps[int(m.group(1))] = (m.group(2), float(m.group(3)), float(m.group(4) or 0))
    cur = None; x = y = 0.0; pol = "D"; region = None
    col = lambda: color if pol == "D" else bg
    for cmd in re.findall(r"%[^%]*%|[^*%\n]+\*", txt):
        cmd = cmd.strip()
        if cmd.startswith("%LP"):
            pol = cmd[3]; continue
        if cmd.startswith("%"):
            continue
        cmd = cmd.rstrip("*")
        if cmd == "G36":
            region = []; continue
        if cmd == "G37":
            ax.add_patch(MPoly(region, closed=True, fc=col(), ec="none")); region = None; continue
        m = re.match(r"^D(\d+)$", cmd)
        if m and int(m.group(1)) >= 10:
            cur = aps[int(m.group(1))]; continue
        m = re.match(r"^X(-?\d+)Y(-?\d+)D0([123])$", cmd)
        if not m:
            continue
        nx, ny, op = int(m.group(1)) / 1e6, -int(m.group(2)) / 1e6, m.group(3)
        if region is not None:
            region.append((nx, ny))
        elif op == "1":
            hw = cur[1] / 2
            L = math.hypot(nx - x, ny - y) or 1e-9
            px, py = -(ny - y) / L * hw, (nx - x) / L * hw
            ax.add_patch(MPoly([(x + px, y + py), (nx + px, ny + py), (nx - px, ny - py), (x - px, y - py)],
                               closed=True, fc=col(), ec="none"))
            ax.add_patch(Circle((x, y), hw, fc=col(), ec="none"))
            ax.add_patch(Circle((nx, ny), hw, fc=col(), ec="none"))
        elif op == "3":
            k, a, b = cur
            if k == "C" or (k == "O" and abs(a - b) < 1e-6):
                ax.add_patch(Circle((nx, ny), a / 2, fc=col(), ec="none"))
            elif k == "O":
                r = min(a, b) / 2
                ax.add_patch(Circle((nx - (a / 2 - r), ny - (b / 2 - r)), r, fc=col(), ec="none"))
                ax.add_patch(Circle((nx + (a / 2 - r), ny + (b / 2 - r)), r, fc=col(), ec="none"))
                w2, h2 = (a / 2 - r, r) if a > b else (r, b / 2 - r)
                ax.add_patch(MPoly([(nx - w2, ny - h2), (nx + w2, ny - h2), (nx + w2, ny + h2), (nx - w2, ny + h2)],
                                   closed=True, fc=col(), ec="none"))
            else:
                ax.add_patch(MPoly([(nx - a / 2, ny - b / 2), (nx + a / 2, ny - b / 2), (nx + a / 2, ny + b / 2),
                                    (nx - a / 2, ny + b / 2)], closed=True, fc=col(), ec="none"))
        x, y = nx, ny


_scale = [1.0]


def preview(gdir, out_png, files, title):
    fig, ax = plt.subplots(figsize=(12, 9), dpi=100)
    ax.set_xlim(BX1 - 1, BX2 + 1); ax.set_ylim(BY2 + 1, BY1 - 1); ax.set_aspect("equal")
    fig.canvas.draw()
    # points per mm for track widths
    bb = ax.get_window_extent()
    _scale[0] = (bb.width / (BX2 - BX1 + 2)) / (fig.dpi / 25.4 * 1.0) / 1.0
    ax.set_facecolor("#1a1a1a")
    for fn, colr, bg in files:
        render_gerber(os.path.join(gdir, fn), ax, colr, bg)
    ax.set_title(title)
    fig.savefig(out_png, bbox_inches="tight")
    plt.close(fig)


