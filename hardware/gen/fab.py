def copper_layer(layer, R, pour_net=None, plane=False):
    func = {"F.Cu": "Copper,L1,Top", "In1.Cu": "Copper,L2,Inr", "In2.Cu": "Copper,L3,Inr",
            "B.Cu": "Copper,L4,Bot"}[layer]
    g = Gerber(func)
    pads = [p for p in placed_pads_cache() if layer in p.layers]
    tracks = [t for t in R["tracks"] if t["layer"] == layer]
    vias = R["vias"]
    npth = [p for p in placed_pads_cache() if p.kind == "np_thru_hole"]
    if pour_net:
        g.region(outline_polygon(0.3, 8))
        g.polarity("C")
        for p in pads:
            if p.net != pour_net:
                draw_pad(g, p, ZONE_CLR)
        for t in tracks:
            if t["net"] != pour_net:
                g.line(t["a"], t["b"], t["w"] + 2 * ZONE_CLR)
        for v in vias:
            if v["net"] != pour_net:
                g.flash_circle(v["at"][0], v["at"][1], v["size"] + 2 * ZONE_CLR)
        for p in npth:
            g.flash_circle(p.x, p.y, p.drill + 2 * 0.5)
        g.polarity("D")
    if not plane:
        for t in tracks:
            g.line(t["a"], t["b"], t["w"])
    for p in pads:
        if plane and p.net != pour_net:
            continue            # inner layers: non-plane pads have no copper (unused pads removed)
        draw_pad(g, p)
    for v in vias:
        if plane and v["net"] != pour_net:
            continue
        g.flash_circle(v["at"][0], v["at"][1], v["size"])
    return g


def mask_layer(side, R):
    g = Gerber("Soldermask,Top" if side == "F" else "Soldermask,Bot", "Negative")
    for p in placed_pads_cache():
        if p.kind == "np_thru_hole":
            g.flash_circle(p.x, p.y, p.drill + 0.1)
            continue
        if side == "B" and p.kind != "thru_hole":
            continue
        draw_pad(g, p, MASK_EXP)
    return g            # vias are tented


def paste_layer(R):
    g = Gerber("Paste,Top", "Positive")
    for p in placed_pads_cache():
        if p.kind == "smd":
            draw_pad(g, p)
    return g


FONT = FontProperties(family="DejaVu Sans")


def text_polys(s, x, y, size, rot):
    tp = TextPath((0, 0), s, size=size * 1.35, prop=FONT)
    polys = tp.to_polygons()
    if not polys:
        return []
    xs = [p[0] for poly in polys for p in poly]
    ys = [p[1] for poly in polys for p in poly]
    cx, cy = (min(xs) + max(xs)) / 2, (min(ys) + max(ys)) / 2
    out = []
    for poly in polys:
        pts = []
        for (px, py) in poly:
            lx, ly = px - cx, -(py - cy)          # text y-up -> board y-down
            dx, dy = rot_pt(lx, ly, rot)
            pts.append((x + dx, y + dy))
        area = sum(pts[i][0] * pts[(i + 1) % len(pts)][1] - pts[(i + 1) % len(pts)][0] * pts[i][1]
                   for i in range(len(pts))) / 2
        out.append((pts, area))
    return out


def silk_layer(meta):
    from write_kicad import BOARD_TEXT
    g = Gerber("Legend,Top")
    pads = placed_pads_cache()
    for ref, part in PARTS.items():
        fx, fy, frot = PLACEMENT[ref]
        f = FOOTPRINTS[part.fp]
        for gr in f.gfx:
            if gr[1] != "F.SilkS":
                continue
            if gr[0] == "line":
                _, L, x1, y1, x2, y2, w = gr
                a = rot_pt(x1, y1, frot); b = rot_pt(x2, y2, frot)
                g.line((fx + a[0], fy + a[1]), (fx + b[0], fy + b[1]), w)
            else:
                _, L, cx, cy, r, w = gr
                c = rot_pt(cx, cy, frot)
                n = 36
                pts = [(fx + c[0] + r * math.cos(2 * math.pi * i / n), fy + c[1] + r * math.sin(2 * math.pi * i / n))
                       for i in range(n + 1)]
                for a, b in zip(pts[:-1], pts[1:]):
                    g.line(a, b, w)
    texts = []
    for ref, s in meta["silk"].items():
        if s:
            texts.append((ref, s[0], s[1], 0.8, s[2]))
    for (t, x, y, sz, rot) in BOARD_TEXT:
        texts.append((t, x, y, sz, rot))
    for (t, x, y, sz, rot) in texts:
        polys = text_polys(t, x, y, sz, rot)
        # matplotlib glyph outer contours come out with positive area in board
        # (y-down) coordinates, counter/hole contours negative
        outer = [p for p, a in polys if a > 0]
        holes = [p for p, a in polys if a <= 0]
        for p in outer:
            g.region(p)
            for a, b in zip(p, p[1:] + p[:1]):      # embolden: KiCad plots 0.15 mm strokes
                g.line(a, b, 0.07)
        if holes:
            g.polarity("C")
            for p in holes:
                g.region(p)
            g.polarity("D")
    # clip silk from exposed pads (as KiCad does)
    g.polarity("C")
    for p in pads:
        if p.kind != "np_thru_hole":
            draw_pad(g, p, MASK_EXP + 0.05)
    g.polarity("D")
    return g


def edge_layer():
    g = Gerber("Profile,NP")
    pts = outline_polygon(0.0, 16)
    for a, b in zip(pts, pts[1:] + pts[:1]):
        g.line(a, b, 0.1)
    return g


def drill_files(R, d):
    pth, npth = {}, {}
    for p in placed_pads_cache():
        if p.drill:
            (npth if p.kind == "np_thru_hole" else pth).setdefault(p.drill, []).append((p.x, p.y))
    for v in R["vias"]:
        pth.setdefault(v["drill"], []).append(tuple(v["at"]))
    for name, tools, plated in [("CAN_ECU-PTH.drl", pth, True), ("CAN_ECU-NPTH.drl", npth, False)]:
        out = ["M48", "; DRILL file - STM32 CAN ECU rev A - generated by hardware/gen/fab.py",
               f"; #@! TF.FileFunction,{'Plated,1,4,PTH' if plated else 'NonPlated,1,4,NPTH'}",
               "FMAT,2", "METRIC,TZ"]
        tl = sorted(tools)
        for i, dia in enumerate(tl):
            out.append(f"T{i + 1}C{dia:.3f}")
        out += ["%", "G90", "G05"]
        for i, dia in enumerate(tl):
            out.append(f"T{i + 1}")
            for x, y in tools[dia]:
                out.append(f"X{x:.3f}Y{gy(y):.3f}")
        out += ["T0", "M30"]
        open(os.path.join(d, name), "w").write("\n".join(out) + "\n")
    return pth, npth


